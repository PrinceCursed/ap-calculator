// Генерирует синтетический пример лога samples/sample-ballas.txt (реальные логи не прикладывались).
// Запуск: node scripts/make-sample.ts
import { writeFileSync } from 'node:fs';

let id = 880000;
const rows: string[] = [];
const seps = ['\t', '\t', '    ', '  ', '   '];
const p = (n: number) => String(n).padStart(2, '0');
function add(time: string, nick: string, text: string, faction = 'The Ballas Gang', date = '09.11.2026') {
  const s = seps[id % seps.length];
  rows.push([String(++id), nick, faction, text, `${date}, ${time}`].join(s));
}
const t = (h: number, m: number, s = 0) => {
  const x = h * 3600 + m * 60 + s;
  return `${p(Math.floor(x / 3600) % 24)}:${p(Math.floor((x % 3600) / 60))}:${p(x % 60)}`;
};
const P = (i: number) => `Gangster_${i} [${20000 + i}]`;

rows.push('Prince — 23:50', 'message.txt', '8 кб');
// Поезд: 12 участников + 239 ящ. (засчитан), 6 участников + 189 ящ. (спорный)
for (let i = 0; i < 12; i++) add(t(18, 0, i * 7), P(i), 'Участвует в нападении на поезд с военным грузом.');
add(t(18, 42), P(1), 'Доставляет грузовик с украденным из поезда грузом (239 ящ.)');
for (let i = 0; i < 6; i++) add(t(21, 0, i * 7), P(i + 20), 'Участвует в нападении на поезд с военным грузом.');
add(t(21, 40), P(20), 'Доставляет грузовик с украденным из поезда грузом (189 ящ.)');
// NG: Army28-33 без ЭМИ; ФЗ: ЭМИ + Army40-43
for (let n = 28; n <= 33; n++) add(t(14, 0, (n - 28) * 25), P(n), `Разгружает 300 материалов из армейского грузовика Army${n}`);
add(t(16, 10), P(3), 'Применяет комплект для ЭМИ на Форте Занкудо.');
for (let n = 40; n <= 43; n++) add(t(16, 35, (n - 40) * 30), P(n), `Разгружает 300 материалов из армейского грузовика Army${n}`);
// EMS
for (let n = 1; n <= 4; n++) add(t(12, 0, n * 12), P(n), `Разгружает 750 аптек из EMS${n} на склад фракции`);
// Граффити 7 побед
for (let i = 0; i < 7; i++) add(t(13, i * 5), P(i), 'Получает $1500 за победу в GRAFFITI WAR');
// Ганшоп
add(t(11, 5), P(2), 'Разгружает 4200 материалов из оружейного магазина');
add(t(11, 50), P(4), 'Разгружает 1800 материалов из оружейного магазина');
// Дома: 33, часть с невидимым U+2060 и решёткой
for (let i = 0; i < 33; i++) add(t(2, i * 2), P(i % 6), i % 2 ? `Взламывает дом #${60 + i}.` : `Взламывает дом ⁠${100 + i}.`);
// Угонки 12
for (let i = 0; i < 12; i++) add(t(3, i * 3), P(i % 4), `Привозит угнанный автомобиль ${['AB', 'KX', 'ZT'][i % 3]}${100 + i}`);
// Ограбления 21
for (let i = 0; i < 21; i++) add(t(4, i * 2), P(i % 7), 'Грабит человека.');
// Аирдроп
for (let i = 0; i < 11; i++) add(t(19, 30, i * 9), P(i), 'Участвует в захвате выпавшего армейского воздушного груза.');
add(t(19, 48), 'SYSTEM [1]', 'Получает припасы из выпавшего армейского груза: 120 патронов, 10 бронежилетов');
// Чёрный рынок — 8 участников (спорный)
for (let i = 0; i < 8; i++) add(t(22, 10, i * 20), P(i), 'Участвует в захвате чёрного рынка.');
// Флаг
add(t(15, 20), P(5), 'Побеждает в бою против The Families в режиме Захват флага');
// Рэкет 10
const kinds = ['Нападает на Магазин 24/7 #12', 'Нападает на Тату салон #3', 'Нападает на Магазин спортивной одежды #2'];
for (let i = 0; i < 10; i++) add(t(10, i * 3), P(i), kinds[i % 3]);
// Шум: другие фракции и даты
for (let i = 0; i < 40; i++) add(t(9, i), `Vago_${i} [${30000 + i}]`, 'Грабит человека.', 'Los Santos Vagos');
for (let i = 0; i < 15; i++) add(t(23, i), P(i), 'Грабит человека.', 'The Ballas Gang', '08.11.2026');

writeFileSync(new URL('../samples/sample-ballas.txt', import.meta.url), rows.join('\n') + '\n');
console.log(`samples/sample-ballas.txt: ${rows.length} строк`);
